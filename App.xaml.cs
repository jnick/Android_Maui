// Подключаем пространство имён сервисного слоя (нужен интерфейс ICameraService для внедрения в конструктор)
using MauiBluethooth.Services;
// Подключаем пространство имён с классами внедрения зависимостей (DI-контейнер)
using Microsoft.Extensions.DependencyInjection;

// Объявляем корневое пространство имён приложения
namespace MauiBluethooth;

// Объявление частичного класса приложения (наследует Application — точка входа MAUI-приложения)
public partial class App : Application
{
	// Камерный сервис, внедрённый контейнером DI.
	// Нужен приложению для обработки ухода в фон и возврата из него: MAUI не умеет
	// освобождать камеру автоматически, а без этого её не откроют другие приложения
	private readonly ICameraService _cameraService;

	// Конструктор приложения. MAUI создаёт App сам и передаёт зависимости из контейнера DI
	public App(ICameraService cameraService)
	{
		// Сохраняем сервис в поле для обработчиков жизненного цикла ниже
		_cameraService = cameraService;

		// Инициализирует компоненты, объявленные в XAML-файле App.xaml (ресурсы, стили)
		InitializeComponent();
	}

	// Приложение уходит в фон (пользователь свернул окно или заблокировал экран)
	protected override async void OnSleep()
	{
		// Вызываем базовую реализацию: MAUI должна обработать переход в фон
		base.OnSleep();

		try
		{
			// Просим сервис освободить камеру.
			// Критично для Android: пока камера занята, система может убить процесс приложения,
			// а другие приложения не смогут её открыть
			await _cameraService.HandleAppSleepAsync();
		}
		catch
		{
			// Приложение сворачивается — падать здесь нельзя: исключение из обработчика
			// жизненного цикла привело бы к аварийному закрытию приложения.
			// Сервис внутри уже обрабатывает свои ошибки, этот catch — страховка
		}
	}

	// Приложение вернулось из фона
	protected override async void OnResume()
	{
		// Вызываем базовую реализацию
		base.OnResume();

		try
		{
			// Просим сервис запустить камеру заново.
			// Сервис сам проверит, нужно ли это: он поднимет камеру, только если
			// пользователь её не выключал и страница камеры всё ещё открыта
			await _cameraService.HandleAppResumeAsync();
		}
		catch
		{
			// Аналогично OnSleep: исключение здесь сломало бы возврат приложения из фона.
			// Состояние камеры пользователь увидит по статусу на экране
		}
	}

	// Метод создания главного окна приложения (вызывается фреймворком)
	protected override Window CreateWindow(IActivationState? activationState)
	{
		// Создаём и возвращаем окно, содержимое которого — экземпляр AppShell
		return new Window(new AppShell());
	}
}