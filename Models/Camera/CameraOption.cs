// Объявляем пространство имён для моделей данных, связанных с камерой
namespace MauiBluethooth.Models.Camera;

// Перечисление: какая сторона камеры обращена к пользователю.
// Нужно, чтобы выбрать камеру по умолчанию (обычно заднюю) и понять, надо ли зеркалить изображение
public enum CameraLensFacing
{
	// Задняя камера — основная, направлена от пользователя
	Rear,

	// Фронтальная камера — направлена на пользователя, её изображение зеркалят
	Front
}

// Описание одной доступной камеры: идентификатор, отображаемое имя и сторона объектива.
// Это модель для выпадающего списка (Picker) выбора камеры
public sealed class CameraOption
{
	// Конструктор описания камеры
	public CameraOption(string id, string name, CameraLensFacing lensFacing)
	{
		// Идентификатор камеры. Формат разный для платформ:
		// Android — «rear»/«front», Windows — «идентификатор_группы:идентификатор_источника»
		Id = id;

		// Человекочитаемое имя камеры, показываем пользователю в Picker
		Name = name;

		// Сторона объектива камеры
		LensFacing = lensFacing;
	}

	// Идентификатор камеры — по нему сервис понимает, какую камеру открыть
	public string Id { get; }

	// Отображаемое имя камеры
	public string Name { get; }

	// Сторона объектива: задняя или фронтальная
	public CameraLensFacing LensFacing { get; }

	// Переопределяем ToString, чтобы Picker показывал имя камеры, а не название типа
	public override string ToString() => Name;
}
