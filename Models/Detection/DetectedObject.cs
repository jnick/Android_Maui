// Подключаем примитивы геометрии MAUI (RectF, PointF, SizeF) —
// это те же структуры, что использует XAML, поэтому координаты удобно передавать в привязки
using Microsoft.Maui.Graphics;

// Объявляем пространство имён для моделей данных распознавания
namespace MauiBluethooth.Models.Detection;

// Что именно распознаёт модель. Нужно UI, чтобы выбирать подпись и цвет рамок
public enum DetectionModelKind
{
	// Детектор лиц (YuNet)
	Face,

	// Детектор объектов из набора COCO (NanoDet, YOLOX)
	Objects,

	// Классический детектор геометрических фигур на обработке изображений (OpenCV)
	Shapes
}

// Вид распознанной геометрической фигуры.
// Вынесен отдельно от DetectedObject, потому что у фигур есть своя типология,
// которой нет в списке классов COCO
public enum ShapeKind
{
	// Круг, найденный преобразованием Хафа
	Circle,

	// Квадрат — контур, у которого четыре угла и примерно равные стороны
	Square,

	// Прямоугольник — контур с четырьмя углами и заметно разными сторонами
	Rectangle,

	// Треугольник — контур с тремя вершинами
	Triangle
}

// Один найденный объект: рамка, подпись, уверенность и (для лиц) точки черт лица.
// Это «готовая к отрисовке» единица: детектор отдаёт её наружу, а UI больше ничего не вычисляет
public sealed record DetectedObject
{
	// Конструктор объекта обнаружения
	public DetectedObject(
		// Рамка в пикселях кадра, в той же системе координат, что и сам кадр на экране
		RectF bounds,
		// Текстовая подпись: имя класса или «Лицо»
		string label,
		// Уверенность модели от 0 до 1
		float confidence)
	{
		// Сохраняем рамку
		Bounds = bounds;

		// Сохраняем подпись
		Label = label;

		// Сохраняем уверенность
		Confidence = confidence;
	}

	// Рамка объекта в пикселях кадра.
	// ВАЖНО: координаты уже в «экранной» системе — с учётом поворота и зеркальности камеры,
	// поэтому overlay умеет только масштабировать их под свой размер
	public RectF Bounds { get; }

	// Подпись объекта, которую рисуем поверх рамки
	public string Label { get; }

	// Уверенность модели: 0..1
	public float Confidence { get; }

	// Ключевые точки лица: правый глаз, левый глаз, нос, оба рта.
	// Для лица их ровно пять, для остальных объектов — пустой список
	public IReadOnlyList<PointF> Landmarks { get; init; } = [];

	// Вид фигуры. Заполняется только детектором фигур, для нейросетей остаётся null
	public ShapeKind? Shape { get; init; }
}

// Неизменяемый снимок результатов по одному кадру.
//
// Зачем он нужен: обработка кадра идёт в фоновом потоке, а рисовать рамки нужно в UI-потоке.
// Снимок — это «общая точка» между ними: фоновая обработка кладёт готовый результат,
// UI забирает последний целиком. Никаких частично обновлённых списков на экране не появится
public sealed record DetectionSnapshot
{
	// Список найденных объектов в порядке убывания уверенности
	public required IReadOnlyList<DetectedObject> Objects { get; init; }

	// Идентификатор модели, которой получен этот снимок
	public required string ModelId { get; init; }

	// Категория модели (лица, объекты, фигуры) — по ней UI выбирает оформление
	public required DetectionModelKind Kind { get; init; }

	// Метка времени кадра, к которому относится результат
	public required long FrameTimestampMilliseconds { get; init; }

	// Ширина кадра в пикселях, в системе координат которой заданы рамки
	public required int FrameWidth { get; init; }

	// Высота кадра в пикселях
	public required int FrameHeight { get; init; }
}
