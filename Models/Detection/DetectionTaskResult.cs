// Подключаем примитивы геометрии MAUI
using Microsoft.Maui.Graphics;

// Объявляем пространство имён для моделей данных распознавания
namespace MauiBluethooth.Models.Detection;

// Зафиксированный результат распознавания — одна строка в журнале заданий.
//
// ЗАЧЕМ ЭТО ОТДЕЛЬНО ОТ DetectionSnapshot.
//
// Снимок отвечает на вопрос «что видно ПРЯМО СЕЙЧАС» и обновляется на каждом кадре.
// Его показывают рамками поверх видео. Но для истории нужно другое: не «что сейчас»,
// а «что было замечено», с отметкой времени.
//
// Если сохранять в журнал каждый кадр, получится мусор: при 15 кадрах в секунду
// за минуту в журнале окажется 900 почти одинаковых строк «найдено лиц: 1».
// Поэтому строка добавляется только тогда, когда СОДЕРЖАНИЕ изменилось:
// появился новый объект, пропал или сменился набор названий
public sealed record DetectionTaskResult
{
	// Момент, когда результат был зафиксирован, в миллисекундах
	public required long TimestampMilliseconds { get; init; }

	// Модель, которой получен результат
	public required string ModelId { get; init; }

	// Человекочитаемое название модели
	public required string ModelDisplayName { get; init; }

	// Найденные объекты этого кадра
	public required IReadOnlyList<DetectedObject> Objects { get; init; }

	// Число находок на момент фиксации
	public int ObjectCount => Objects.Count;

	// Есть ли находки вообще.
	//
	// Отдельное булево свойство, а не сравнение ObjectCount в XAML, потому что
	// для проверки «больше ли нуля» в разметке понадобился бы конвертер,
	// а конвертеров в проекте пока нет
	public bool HasObjects => Objects.Count > 0;

	// Рамка всего найденного.
	//
	// Зачем она нужна: результат на странице заданий должен показывать то же самое,
	// что и рамки на видео, иначе у пользователя возникнет вопрос «почему тут
	// три объекта, а в кадре было пять». Здесь мы рамку НЕ рисуем — она нужна
	// только для хранения, а отрисовкой занимается оверлей камеры
	public RectF? Bounds
	{
		// Рамка вычисляется только если есть хоть одна находка
		get
		{
			// Ничего не нашли — рамки нет
			if (Objects.Count == 0)
			{
				// null означает «нет данных», в отличие от пустой рамки
				return null;
			}

			// Ищем общий прямоугольник, вмещающий все находки
			var left = float.MaxValue;
			var top = float.MaxValue;
			var right = float.MinValue;
			var bottom = float.MinValue;

			// Проходим по всем находкам
			foreach (var item in Objects)
			{
				// Расширяем общую рамку слева и сверху
				left = Math.Min(left, item.Bounds.Left);
				top = Math.Min(top, item.Bounds.Top);

				// И справа, и снизу
				right = Math.Max(right, item.Bounds.Right);
				bottom = Math.Max(bottom, item.Bounds.Bottom);
			}

			// Собираем итоговую рамку
			return new RectF(left, top, right - left, bottom - top);
		}
	}

	// Подпись для списка: перечисление найденных названий.
	//
	// Пустая строка, а не «ничего не найдено»: в списке заданий пустую строку
	// показывать незачем, а вот отдельные строки про отсутствие находок
	// пользователю полезны — их записывает вызывающий код
	public string LabelsText
	{
		get
		{
			// Собираем названия в одну строку через запятую
			var labels = new List<string>(Objects.Count);

			// Проходим по всем находкам
			foreach (var item in Objects)
			{
				// Добавляем название
				labels.Add(item.Label);
			}

			// Склеиваем
			return string.Join(", ", labels);
		}
	}

	// Сводка результата для заголовка списка
	public string SummaryText
	{
		get
		{
			// Ничего не нашли — так и пишем прямо
			if (Objects.Count == 0)
			{
				// Пустой результат
				return "Находок нет";
			}

			// Одна находка — единственное число
			if (Objects.Count == 1)
			{
				// Без «объектов», иначе выходит неграмотно: «1 объектов»
				return "Найдено 1: " + Objects[0].Label;
			}

			// Несколько находок — со счётом
			return $"Найдено: {Objects.Count}";
		}
	}
}