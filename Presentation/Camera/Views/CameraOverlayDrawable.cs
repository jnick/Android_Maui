// Подключаем нашу модель геометрии кадра (CameraFrameGeometry)
using MauiBluethooth.Models.Camera;
// Подключаем нашу модель найденного объекта (DetectedObject)
using MauiBluethooth.Models.Detection;
// Подключаем абстракцию рисования MAUI: ICanvas (поверхность), IDrawable (что рисовать), RectF, Colors
using Microsoft.Maui.Graphics;

// Объявляем пространство имён для представлений раздела «Камера»
namespace MauiBluethooth.Presentation.Camera.Views;

// Оверлей камеры: рисует поверх видео рамки вокруг найденных объектов.
//
// Реализует IDrawable — контракт MAUI для объектов, которые рисуются на GraphicsView.
// MAUI вызывает Draw автоматически при появлении элемента и после вызова Invalidate().
//
// ОБ ОДНОЙ ВАЖНОЙ ДОГОВОРЁННОСТИ С ДЕТЕКТОРОМ.
// Детектор отдаёт координаты рамок УЖЕ в экранной ориентации: кадр предварительно
// повёрнут и, для фронтальной камеры, отражён. Поэтому здесь НЕЛЬЗЯ отражать
// координаты повторно — рамки «уедут» на другую сторону картинки.
// Именно поэтому в этом файле нет проверки IsMirrored, хотя в прошлой версии
// оверлея она была: тогда координаты приходили из демонстрационной заглушки
public sealed class CameraOverlayDrawable : IDrawable
{
	// Делегат, возвращающий текущую геометрию кадра.
	// Передаётся функцией (а не самим объектом), потому что на момент создания оверлея
	// геометрии ещё нет — она появляется только с первым кадром.
	// Func вместо ссылки на ViewModel: оверлей не зависит от модели представления
	private readonly Func<CameraFrameGeometry?> _geometryProvider;

	// Делегат, возвращающий текущий список найденных объектов.
	// Также функция, а не ссылка: оверлей должен получать свежий список
	// на момент перерисовки, а не тот, что был при создании
	private readonly Func<IReadOnlyList<DetectedObject>> _detectionsProvider;

	// Минимальная ширина прямоугольника на экране, в единицах экрана.
	// Нужна, чтобы крошечные рамки вдалеке всё равно было видно как точку,
	// а не как неразличимую полоску в один пиксель
	private const float MinimumBoxSize = 3f;

	// Шрифт подписи на экране
	private const float LabelFontSize = 14f;

	// Сколько объектов можно подписать на одном кадре.
	// Рамки рисуются всем, а текст — только самым крупным: когда объектов много,
	// надписи на каждом лишь превращают экран в кашу, в которой не видно ни рамок, ни видео
	private const int MaxLabeledBoxes = 8;

	// Конструктор оверлея: страница передаёт сюда функции получения
	// геометрии кадра и списка найденных объектов
	public CameraOverlayDrawable(
		Func<CameraFrameGeometry?> geometryProvider,
		Func<IReadOnlyList<DetectedObject>> detectionsProvider)
	{
		// Сохраняем делегат геометрии для вызова при каждой перерисовке
		_geometryProvider = geometryProvider;

		// Сохраняем делегат списка объектов
		_detectionsProvider = detectionsProvider;
	}

	// Метод рисования. Вызывается MAUI: при появлении элемента и при каждом Invalidate()
	public void Draw(ICanvas canvas, RectF dirtyRect)
	{
		// Получаем актуальную геометрию кадра
		var geometry = _geometryProvider();

		// Если кадров ещё не было (null) или размеры некорректны — рисовать нечего.
		// Деление на ширину/высоту кадра ниже дало бы деление на ноль, поэтому проверка обязательна
		if (geometry is null || geometry.DisplayWidth <= 0 || geometry.DisplayHeight <= 0)
		{
			// Возвращаемся: рамки рисовать не по чему
			return;
		}

		// Берём список найденных объектов
		var detections = _detectionsProvider();

		// Пустой список — тоже нечего рисовать.
		// Проверка нужна и для скорости: пустой цикл на каждый Invalidate
		// всё равно лишняя работа, хотя и небольшая
		if (detections is null || detections.Count == 0)
		{
			// Найдено пусто — оставляем только видео
			return;
		}

		// Ширина кадра ПОСЛЕ поворота (DisplayWidth, а не Width):
		// в координатах кадра пиксели повёрнуты, и оверлей обязан учитывать это
		var frameWidth = geometry.DisplayWidth;

		// Высота кадра после поворота
		var frameHeight = geometry.DisplayHeight;

		// КОЭФФИЦИЕНТ МАСШТАБА: во сколько раз пиксели кадра больше единичных экранных единиц.
		// Используем Math.Max, а не Math.Min — это принципиально важно:
		// при Math.Min кадр целиком помещался бы в экран (письмо), а нам нужно,
		// чтобы видео заполняло экран и обрезалось — именно так работает
		// Stretch.UniformToFill, выбранный в WindowsCameraService и в PreviewView на Android.
		// Тогда оверлей и видео масштабируются ОДНИМ И ТЕМ ЖЕ коэффициентом и остаются совмещёнными
		var scale = Math.Max(dirtyRect.Width / frameWidth, dirtyRect.Height / frameHeight);

		// Горизонтальное смещение: (свободное место по ширине) / 2.
		// Так кадр центрируется в элементе, а лишнее по краям обрезается
		var offsetX = (dirtyRect.Width - frameWidth * scale) / 2;

		// Вертикальное смещение — аналогично, по высоте
		var offsetY = (dirtyRect.Height - frameHeight * scale) / 2;

		// Определяем порядок отрисовки: сначала самые крупные на экране рамки.
		// Сортируем по площади, а не как пришли, потому что порядок в списке
		// зависит от модели и между кадрами «прыгает»
		var ordered = detections
			.OrderByDescending(static detection => detection.Bounds.Width * detection.Bounds.Height)
			.ToArray();

		// Рисуем каждый найденный объект по очереди
		for (var i = 0; i < ordered.Length; i++)
		{
			// Очередной объект — самый крупный сначала
			var detection = ordered[i];
			// Прямоугольник объекта приходит в пикселях кадра, в экранной ориентации
			var bounds = detection.Bounds;

			// Переводим прямоугольник из координат кадра в координаты холста (экрана):
			// экранная = смещение + кадровая координата * коэффициент масштаба.
			// Смещение нужно, потому что кадр центрирован и не совпадает с границами элемента
			var left = offsetX + bounds.X * scale;
			var top = offsetY + bounds.Y * scale;
			var width = bounds.Width * scale;
			var height = bounds.Height * scale;

			// ЗАЩИТА ОТ ВЫРОЖДЕННЫХ РАЗМЕРОВ. Сеть иногда возвращает рамку
			// шириной в долю пикселя. После масштабирования такая рамка не видна
			// вообще, и пользователь решит, что детектор не работает.
			// Поэтому подгоняем под минимальный размер — так «точка» видна всегда
			if (width < MinimumBoxSize)
			{
				// Расширяем по ширине до минимального размера
				width = MinimumBoxSize;
			}

			// То же самое по высоте
			if (height < MinimumBoxSize)
			{
				// Расширяем по высоте до минимального размера
				height = MinimumBoxSize;
			}

			// Цвет рамки зависит от уверенности модели: чем выше, тем «спокойнее» цвет.
			// Так на экране сразу видно, где результат надёжный, а где сомнительный
			canvas.StrokeColor = GetConfidenceColor(detection.Confidence);

			// Толщина обводки в пикселях экрана. Фиксированная (не масштабируется от кадра),
			// чтобы рамка не выглядела слишком жирной на маленьком кадре и слишком тонкой на большом
			canvas.StrokeSize = 3;

			// Рисуем рамку. DrawRectangle принимает Left/Top/Width/Height по отдельности,
			// хотя у RectF те же значения уже посчитаны
			canvas.DrawRectangle(left, top, width, height);

			// Цвет текста подписи — белый, чтобы читался на любом фоне
			canvas.FontColor = Colors.White;

			// Подписываем только крупные рамки: когда объектов больше лимита,
			// надписи на всех лишь замусорят экран. Рамку тем временем рисуем каждому
			if (i < MaxLabeledBoxes)
			{
				// Размер шрифта подписи в пикселях экрана
				canvas.FontSize = LabelFontSize;

				// Подписываем объект: название класса и уверенность в процентах.
				// Смещение +4/+4 — небольшой отступ от рамки внутрь.
				// Выравнивание по левому краю: подпись начинается с левой стороны текста,
				// то есть позиция x — это начало строки, а не её центр
				canvas.DrawString(
					$"{detection.Label} {detection.Confidence:P0}",
					left + 4,
					top + 4,
					HorizontalAlignment.Left);
			}
		}
	}

	// Подбирает цвет рамки по уверенности модели.
	//
	// Смысл подбора: при пороге около 50 процентов и выше рамки уверенных
	// находок должны быть спокойного зелёного цвета, а сомнительные — заметно
	// жёлтые. Иначе на экране будет каша из ярких рамок, и главное —
	// невозможно отличить «модель уверена» от «модель ошиблась»
	private static Color GetConfidenceColor(float score)
	{
		// Высокая уверенность: спокойный зелёный
		if (score >= 0.7f)
		{
			// Возвращаем зелёный
			return Color.FromRgb(0.20f, 0.85f, 0.40f);
		}

		// Средняя уверенность: жёлтый — «похоже на правду, но проверьте»
		if (score >= 0.4f)
		{
			// Возвращаем жёлтый
			return Color.FromRgb(0.95f, 0.80f, 0.20f);
		}

		// Низкая уверенность: оранжевый — рамка почти наверняка ложная
		return Color.FromRgb(0.98f, 0.55f, 0.20f);
	}
}
