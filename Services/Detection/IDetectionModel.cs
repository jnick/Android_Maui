// Подключаем OpenCV — детектор работает с матрицами
using OpenCvSharp;

// Подключаем наши модели данных
using MauiBluethooth.Models.Detection;

// Объявляем пространство имён для сервисов распознавания
namespace MauiBluethooth.Services.Detection;

// Единый контракт любой модели распознавания.
//
// Зачем интерфейс, если моделей шесть. Нейросети и классический детектор фигур
// устроены совершенно по-разному, но для камеры и интерфейса это не имеет значения:
// они оба умеют превратить кадр в список рамок. Единственное, что их различает, —
// набор этапов замера времени, поэтому он вынесен в отдельное свойство,
// а не смешан с общим контрактом вызова
public interface IDetectionModel : IDisposable
{
	// Описание модели: идентификатор, название, категория, размер входа
	ModelDescriptor Descriptor { get; }

	// Замеры последнего вызова Detect — по этапам, чтобы видеть, где именно потерялось время.
	// Заполняется самой моделью и читается детектором сразу после вызова
	IReadOnlyList<TimingStage> LastStages { get; }

	// Распознаёт объекты в кадре.
	//
	// Параметры:
	//   bgrFrame        — кадр в формате BGR, УЖЕ в экранной ориентации
	//                     (с учётом поворота и зеркальности камеры);
	//   scoreThreshold  — порог уверенности, обычно берётся из ползунка интерфейса;
	//   results         — список, который модель заполняет заново.
	//
	// Список передаётся снаружи специально: пересоздавать его в каждом кадре — это
	// лишняя сборка мусора, а на телефоне это напрямую съедает кадры в секунду.
	// Считается, что список перед вызовом пуст; модель очищает его сама
	void Detect(Mat bgrFrame, float scoreThreshold, List<DetectedObject> results);
}
