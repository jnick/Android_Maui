// Подключаем математические структуры OpenCV
using OpenCvSharp;

// Подключаем геометрию интерфейса для DetectedObject
using Microsoft.Maui.Graphics;

// ВНИМАНИЕ: и в OpenCvSharp, и в Microsoft.Maui.Graphics есть структура Point.
// Без псевдонима компилятор не может выбрать нужную, поэтому точки контуров
// OpenCV везде пишутся как CvPoint. Так сразу видно, для какой библиотеки объект
using CvPoint = OpenCvSharp.Point;

// Подключаем наши модели данных
using MauiBluethooth.Models.Detection;

// Объявляем пространство имён для конкретных моделей распознавания
namespace MauiBluethooth.Services.Detection.Models;

// Детектор геометрических фигур на классических методах обработки изображений.
//
// ЗАЧЕМ ЭТОТ ФАЙЛ, ЕСЛИ ЕСТЬ НЕЙРОСЕТИ. По трём причинам, и все три важны.
//
// 1) Контрольная группа. Нейросеть можно оценить только сравнением с чем-то.
//    Нейросеть умеет распознавать объекты, для которых нет шаблонов, но
//    геометрические фигуры она как раз распознаёт хуже всего: круг, нарисованный
//    слегка неровно, для сети — это уже не круг. Классические методы справляются
//    с ними идеально, и на таком простом материале сразу видно, что в НЕЙРОСЕТИ
//    или в НАШЕМ КОДЕ ошибка, а не в самой задаче.
//
// 2) Скорость. Здесь нет ни одной свёртки: только преобразование цветов, фильтр
//    и контуры. Такая обработка на телефоне занимает единицы миллисекунд против
//    десятков у нейросети. Хороший наглядный пример того, чем приходится платить
//    за нейросети.
//
// 3) Понимание. Показывает, как выглядит распознавание «по-старому», до нейросетей:
//    цвет → маска → контуры → признаки → решение. Понимание этих шагов помогает
//    потом осмысленно читать декод нейросети, где те же идеи, но спрятаны в веса
public sealed class ClassicalShapeModel : IDetectionModel
{
	// Наименьший размер фигуры в пикселях стороны.
	// Всё меньше этого считаем шумом: пылью на объективе, дрожанием картинки.
	// Значение подобрано так, чтобы на кадре 720p пропускать именно мусор,
	// а не настоящие маленькие фигуры
	private const int MinShapeSize = 24;

	// Наибольший размер фигуры. Всё крупнее — скорее всего это фон или близкая
	// стена, а не нарисованная фигура
	private const int MaxShapeSize = 900;

	// Порог площади: контур должен занимать не меньше этой доли от квадрата
	// своей описанной рамки. У круга отношение площади к площади описанного
	// квадрата равно π/4 ≈ 0,785, у квадрата — 1, у треугольника — 0,5.
	// Порог 0,45 отделяет настоящие фигуры от произвольных клякс
	private const double MinAreaRatio = 0.45;

	// Параметры преобразования Хафа для кругов.
	//
	// dp = 1 означает, что разрешение результата совпадает с разрешением картинки.
	// При dp = 2 результат вдвое грубее и вчетверо быстрее, но мелкие круги
	// находятся хуже. Ставим 1: кругов обычно немного, а качество важнее
	private const double HoughDp = 1.0;

	// Минимальное расстояние между центрами найденных кругов, в пикселях.
	// Без этого ограничения один и тот же круг находится десятком перекрывающихся
	// окружностей, и на экране появляется каша из колец
	private const double HoughMinDist = 30.0;

	// Порог по градиенту яркости при поиске окружностей. Чем ниже значение,
	// тем больше слабых окружностей находится — и тем больше ложных срабатываний
	private const double HoughParam1 = 100.0;

	// Порог по длине окружности. Второй параметр того же преобразования
	private const double HoughParam2 = 20.0;

	// Допуск, с которым длины сторон прямоугольника считаются равными.
	// Для квадрата отношение длин сторон равно единице; 0,2 означает «отличаются
	// не больше чем на пятую часть»
	private const float SquareAspectTolerance = 0.2f;

	// Замеры последнего вызова Detect
	private readonly List<TimingStage> _stages = [];

	// Конструктор модели
	public ClassicalShapeModel(ModelDescriptor descriptor)
	{
		// Сохраняем описание модели
		Descriptor = descriptor;
	}

	// Описание модели
	public ModelDescriptor Descriptor { get; }

	// Замеры последнего распознавания
	public IReadOnlyList<TimingStage> LastStages => _stages;

	// Находит круги, квадраты, прямоугольники и треугольники в кадре
	public void Detect(Mat bgrFrame, float scoreThreshold, List<DetectedObject> results)
	{
		// Наполняем результат заново
		results.Clear();

		// Обнуляем замеры прошлого кадра
		_stages.Clear();

		// Запоминаем момент старта. Этот метод не использует сеть,
		// поэтому замеров тут меньше, чем у нейросетей
		var start = DetectionDiagnostics.Clock.Elapsed.TotalMilliseconds;

		// Строим серый кадр сразу, в самом начале.
		// Преобразование Хафа принимает только одноканальное изображение
		// (CV_8UC1): кормить его цветным BGR-кадром нельзя — OpenCV бросит
		// исключение о неверном типе. Тот же серый кадр ниже понадобится
		// ещё раз, для маски контуров, поэтому строим один раз и переиспользуем
		using var gray = new Mat();
		Cv2.CvtColor(bgrFrame, gray, ColorConversionCodes.BGR2GRAY);

		// Запоминаем момент старта замеров кругов
		var circlesStart = DetectionDiagnostics.Clock.Elapsed.TotalMilliseconds;

		// ШАГ 1. Находим круги.
		//
		// Преобразование Хафа для окружностей ищет не форму, а голоса:
		// каждый пиксель голосует за все окружности, проходящие через него,
		// а окружность, за которую проголосовали все точки, набирает максимум.
		// Отсюда важное свойство: метод находит не «круг нарисованный ровно»,
		// а «окружность, на которую похож объект» — с запасом на неровности.
		// Именно поэтому он справляется с нарисованным от руки кругом,
		// с которым нейросеть спотыкается.
		//
		// Вход — серый кадр, построенный выше: Хаф работает только
		// с одноканальным изображением
		var circles = Cv2.HoughCircles(
			gray,
			HoughModes.Gradient,
			dp: HoughDp,
			minDist: HoughMinDist,
			param1: HoughParam1,
			param2: HoughParam2,
			minRadius: MinShapeSize / 2,
			maxRadius: MaxShapeSize / 2);

		// Результат может быть пустым — на картинке может не быть ни одного круга.
		// Это обычная ситуация, а не ошибка
		if (circles is not null)
		{
			// Каждый найденный круг — тройка чисел: центр X, центр Y, радиус
			for (var i = 0; i < circles.Length; i++)
			{
				// Забираем тройку очередного круга.
				// У круга в OpenCV нет отдельных полей X и Y: центр хранится
				// одной точкой в поле Center, а радиус — в поле Radius
				var circle = circles[i];

				// Уверенность у круга нет: преобразование Хафа не даёт вероятностей.
				// Но приравнивать её к единице нельзя — тогда ползунок порога и цвет
				// рамок перестают работать, а экран заваливает мусором.
				// Считаем псевдоуверенность по доле тёмных пикселей на самой окружности:
				// у нарисованного карандашом круга кольцо почти сплошь тёмное
				var confidence = EstimateCircleConfidence(gray, circle);

				// Уверенность ниже порога — пропускаем.
				// Формально это сравнение бессмысленно (порог может быть 0,9),
				// но оно нужно, чтобы единый ползунок работал одинаково
				// для всех моделей и не ломал интерфейс
				if (confidence < scoreThreshold)
				{
					// Круг не проходит по общему порогу
					continue;
				}

				// Собираем рамку круга: из центра и радиуса
				results.Add(new DetectedObject(
					bounds: new RectF(
						(float)(circle.Center.X - circle.Radius),
						(float)(circle.Center.Y - circle.Radius),
						(float)(circle.Radius * 2),
						(float)(circle.Radius * 2)),
					label: "Круг",
					confidence: confidence)
				{
					// Помечаем вид фигуры, чтобы интерфейс знал, чем её рисовать
					Shape = ShapeKind.Circle
				});
			}
		}

		// Замеряем круг: преобразование Хафе — самая тяжёлая часть этого метода
		_stages.Add(new TimingStage("Круги (Хаф)", DetectionDiagnostics.Clock.Elapsed.TotalMilliseconds - circlesStart));

		// ШАГ 2. Находим фигуры с углами по контурам.
		//
		// Здесь другой принцип. Сначала превращаем картинку в маску «тёмное или нет»,
		// потом обходим границы всех однотонных пятен. У круга углов нет вообще,
		// у треугольника — три, у квадрата и прямоугольника — четыре.
		// Число углов и почти равенство сторон и есть признаки, по которым
		// контур превращается в название фигуры
		var maskStart = DetectionDiagnostics.Clock.Elapsed.TotalMilliseconds;

		// Строим маску по яркости — на том же сером кадре, что и Хаф выше.
		// Порог 80 — середина диапазона 0..255. Всё темнее 80 считаем «фигурой».
		// Для нарисованных на бумаге фигур это работает: бумага светлая,
		// линии тёмные. Значение порога — единственный «настроечный» параметр
		// всего метода, и его приходится подбирать под условия съёмки.
		// Бинаризуем: пиксели темнее порога становятся белыми (255),
		// остальные — чёрными. Именно наоборот, чем кажется на первый взгляд:
		// для FindContours ищутся БЕЛЫЕ области на ЧЁРНОМ фоне
		using var mask = new Mat();
		Cv2.Threshold(gray, mask, 80, 255, ThresholdTypes.Binary);

		// Находим контуры. RETR_EXTERNAL берёт только внешние границы —
		// внутренние контуры букв внутри надписи нам не нужны
		Cv2.FindContours(
			mask,
			out CvPoint[][] contours,
			out _,
			RetrievalModes.External,
			ContourApproximationModes.ApproxSimple);

		// Замеряем построение маски и поиск контуров
		_stages.Add(new TimingStage("Контуры", DetectionDiagnostics.Clock.Elapsed.TotalMilliseconds - maskStart));

		// ШАГ 3. Превращаем контуры в фигуры по числу углов
		var analyseStart = DetectionDiagnostics.Clock.Elapsed.TotalMilliseconds;

		// Список найденных контуров
		// Работаем по контуру, пропуская мелкие, растянутые и пустые
		foreach (var contour in contours)
		{
			// У контура должен быть хотя бы один пиксель, иначе с ним нечего делать
			if (contour.Length < 1)
			{
				// Пустой контур — пропускаем
				continue;
			}

			// Площадь контура в пикселях.
			// ВАЖНО: это НЕ длина контура, а площадь фигуры внутри него.
			// Утверждение contour.Length — это как раз типичная ошибка:
			// контур квадрата 30×30 имеет всего четыре точки, но площадь 900
			var area = Math.Abs(Cv2.ContourArea(contour));

			// Отбрасываем совсем мелкие пятна: пыль, дрожание, артефакты сжатия
			if (area < MinShapeSize * MinShapeSize * 0.5)
			{
				// Слишком мелкое пятно — не фигура
				continue;
			}

			// Упрощаем контур.
			//
			// Что делает ApproxPolyDP: идёт по контуру и отбрасывает точки,
			// поворот которых «незначителен», пока их не останется столько,
			// сколько углов у настоящей фигуры. У круга останется много точек
			// (у него нет углов), у квадрата — четыре, у треугольника — три.
			// Второй параметр — допуск: чем он больше, тем грубее упрощение
			var simplified = Cv2.ApproxPolyDP(contour, 0.03 * Cv2.ArcLength(contour, true), true);

			// Описывающий прямоугольник в повёрнутом виде.
			// Именно повёрнутый: нарисованный ромб должен попасть в «квадрат»,
			// а обычный описывающий прямоугольник дал бы для него сильно
			// вытянутый прямоугольник с отношением сторон около двух
			var rotatedRect = Cv2.MinAreaRect(contour);

			// Короткая и длинная стороны описанного прямоугольника
			var shortSide = Math.Min(rotatedRect.Size.Width, rotatedRect.Size.Height);
			var longSide = Math.Max(rotatedRect.Size.Width, rotatedRect.Size.Height);

			// Отсекаем по размеру: слишком мелкие и слишком крупные пропускаем
			if (shortSide < MinShapeSize || longSide > MaxShapeSize)
			{
				// Не тот размер — не фигура
				continue;
			}

			// Считаем отношение большей стороны к меньшей.
			// Для квадрата это примерно 1, для прямоугольника — заметно больше
			var aspect = shortSide > 0f ? longSide / shortSide : 0f;

			// Площадь описанного прямоугольника нужна, чтобы отсечь кляксы:
			// у настоящей фигуры площадь составляет заметную долю этого прямоугольника
			var boundingArea = rotatedRect.Size.Width * rotatedRect.Size.Height;
			if (boundingArea <= 0f)
			{
				// Вырожденный прямоугольник — пропускаем
				continue;
			}

			// Отношение площади фигуры к площади описанного прямоугольника
			var areaRatio = area / boundingArea;

			// У кляксы это отношение мало: контур рваный и заполняет
			// прямоугольник едва-едва
			if (areaRatio < MinAreaRatio)
			{
				// Слишком «пустая» фигура — пропускаем
				continue;
			}

			// Собираем рамку фигуры в координатах кадра.
			// MinAreaRect даёт четыре угла повёрнутого прямоугольника,
			// но нам нужен обычный прямоугольник по четырём крайним точкам
			var box = Cv2.BoundingRect(contour);

			// Определяем вид фигуры по числу углов упрощённого контура
			var shape = ClassifyByVertexCount(simplified.Length);

			// Круг здесь не обрабатываем: окружность с большим числом углов —
			// это тот же круг, который уже найден преобразованием Хафа выше.
			// Повторная рамка на том же месте только замусорила бы экран
			if (shape == ShapeKind.Circle)
			{
				// Круг оставляем Хафу
				continue;
			}

			// У четырёхугольника нужно ещё посмотреть на пропорции:
			// квадрат и прямоугольник отличаются только ими
			if (shape == ShapeKind.Square && aspect > 1f + SquareAspectTolerance)
			{
				// Четыре угла есть, но стороны заметно разные — это прямоугольник
				shape = ShapeKind.Rectangle;
			}

			// Уверенность классических методов не «настоящая» вероятность, но дать
			// единицу всем нельзя: тогда ползунок порога и подсветка рамок перестают
			// работать. Считаем псевдоуверенность по близости площади контура
			// к идеальной доле описанного прямоугольника для данного вида фигуры
			var confidence = (float)Math.Clamp(areaRatio / IdealAreaRatio(shape), 0f, 1f);

			// Общий порог из интерфейса здесь почти не работает: у классики
			// нет понятия уверенности. Проверка оставлена ради единого поведения
			// всех моделей в интерфейсе
			if (confidence < scoreThreshold)
			{
				// Не проходит общий порог
				continue;
			}

			// Добавляем найденную фигуру в результат
			results.Add(new DetectedObject(
				bounds: new RectF(box.X, box.Y, box.Width, box.Height),
				label: GetShapeName(shape),
				confidence: confidence)
			{
				// Помечаем вид фигуры для интерфейса
				Shape = shape
			});
		}

		// Замеряем разбор контуров
		_stages.Add(new TimingStage("Разбор фигур", DetectionDiagnostics.Clock.Elapsed.TotalMilliseconds - analyseStart));
	}

	// Определяет вид фигуры по числу углов упрощённого контура.
	//
	// Порядок проверки важен: сначала самые строгие случаи.
	// Контур треугольника может упроститься до четырёх точек, если одна из вершин
	// попала на границу допуска, поэтому «четыре угла» проверяем в последнюю очередь
	private static ShapeKind ClassifyByVertexCount(int vertexCount) => vertexCount switch
	{
		// Примерно три вершины — треугольник
		3 => ShapeKind.Triangle,

		// Четыре или пять вершин. Пять — это обычно прямоугольник, у которого
		// ApproxPolyDP не срезал одну из сторон полностью
		4 or 5 => ShapeKind.Square,

		// Восемь углов бывает у слегка скруглённого прямоугольника
		8 => ShapeKind.Rectangle,

		// Много углов — это скорее всего круг: у окружности углов нет,
		// и при упрощении остаётся много точек. Круг уже найден выше
		// преобразованием Хафа, поэтому здесь его просто пропускаем
		_ => ShapeKind.Circle
	};

	// Возвращает подпись вида фигуры
	private static string GetShapeName(ShapeKind shape) => shape switch
	{
		// Круг
		ShapeKind.Circle => "Круг",

		// Квадрат
		ShapeKind.Square => "Квадрат",

		// Прямоугольник
		ShapeKind.Rectangle => "Прямоугольник",

		// Треугольник
		ShapeKind.Triangle => "Треугольник",

		// Неизвестный вид — заглушка, чтобы интерфейс не упал на новом значении перечисления
		_ => "Фигура"
	};

	// Считает псевдоуверенность круга по доле тёмных пикселей на его окружности.
	//
	// Зачем это нужно. Хаф не даёт вероятностей, поэтому кругам нужен *какой-то* скор,
	// иначе ползунок порога и подсветка рамок перестают работать, а весь мусор —
	// блики, тени, края предметов — рисуется как настоящий круг. Нарисованный
	// карандашом круг на светлой бумаге — это тёмное кольцо: большая часть точек
	// окружности будет темнее порога маски. У ложного срабатывания такого кольца нет
	private static float EstimateCircleConfidence(Mat gray, CircleSegment circle)
	{
		// Порог яркости такой же, как при построении маски контуров.
		// Константа вынесена отдельно от маски, потому что метод маски
		// использует Threshold, а здесь достаточно простого сравнения пикселя
		const byte DarkThreshold = 80;

		// Радиус круга. Отрицательный или нулевой Хаф вернуть не должен,
		// но защита от деления на ноль дешевле, чем полёт после такой находки
		var radius = circle.Radius;
		if (radius <= 0f)
		{
			// Вырожденный круг — считаем неподтверждённым
			return 0f;
		}

		// Число точек на окружности. Чем больше, тем точнее оценка,
		// но и тем дороже. Шаг 5 градусов — 72 точки, достаточно для круга
		const int samples = 72;

		// Счётчики: всего точек в границах кадра и тёмных среди них
		var inside = 0;
		var dark = 0;

		// Проходим по окружности с шагом в 5 градусов
		for (var i = 0; i < samples; i++)
		{
			// Текущий угол в радианах
			var angle = i * 2 * Math.PI / samples;

			// Координата точки на окружности: центр плюс радиус по направлению угла
			var x = circle.Center.X + radius * Math.Cos(angle);
			var y = circle.Center.Y + radius * Math.Sin(angle);

			// Точка должна попадать в границы кадра, иначе сравнивать её нельзя
			if (x < 0 || y < 0 || x >= gray.Cols || y >= gray.Rows)
			{
				// Точка вне кадра — просто пропускаем, доля считается по видимым
				continue;
			}

			// Точка учтена при подсчёте доли
			inside++;

			// Тёмный ли пиксель на этой точке
			if (gray.At<byte>((int)y, (int)x) <= DarkThreshold)
			{
				// Пиксель темнее порога — это часть тёмного кольца
				dark++;
			}
		}

		// Ни одной видимой точки — круг целиком за границей кадра, подтвердить нечем
		if (inside == 0)
		{
			// Возвращаем полное недоверие
			return 0f;
		}

		// Псевдоуверенность — доля тёмных точек на видимой части окружности
		return (float)dark / inside;
	}

	// Возвращает идеальную долю площади фигуры от площади описанного прямоугольника.
	//
	// Нужна для псевдоуверенности контурных фигур: чем ближе реальная доля
	// к идеальной, тем увереннее мы в фигуре. Значения взяты из комментария
	// к MinAreaRatio: у треугольника ≈ 0,5, у квадрата и прямоугольника ≈ 1
	private static double IdealAreaRatio(ShapeKind shape) => shape switch
	{
		// У треугольника площадь составляет примерно половину описанного прямоугольника
		ShapeKind.Triangle => 0.5,

		// У квадрата и прямоугольника площадь почти занимает весь описанный прямоугольник
		ShapeKind.Square or ShapeKind.Rectangle => 1.0,

		// Круг сюда не попадает — его обрабатывает Хаф. Значение для прочих видов
		// оставляем нейтральным, чтобы не сломать расчёт при будущих видах
		_ => 1.0
	};

	// Классической модели нечего освобождать: ни сети, ни нативной памяти у неё нет
	public void Dispose()
	{
		// Пустая реализация: класс IDisposable требует метод, даже если освобождать нечего
	}
}
