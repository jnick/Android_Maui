// Подключаем OpenCV
using OpenCvSharp;

// Объявляем пространство имён для моделей распознавания
namespace MauiBluethooth.Services.Detection.Models;

// Чтение выходов нейросети.
//
// Выход OpenCV DNN — это обычный Mat, но с нюансами: у моделей он бывает
// трёхмерным (например, [1, 8400, 85] у YOLOX) и хранится как float32.
// Обращаться к нему по одному элементу через Mat.At нельзя — это вызов через
// interop на каждое число, а в YOLOX таких чисел почти 700 тысяч.
// Поэтому читаем данные одним куском и считаем индексы руками
internal static class DnnOutput
{
	// Приводит выход сети к непрерывному массиву float.
	//
	// Почему здесь Span, а не копия в float[]: у YOLOX выход это
	// 1 × 8400 × 85 = 714 000 значений. Копировать их в новый массив каждый кадр —
	// это примерно 2,8 МБ мусора на кадр, и сборщик мусора на телефоне начнёт
	// заметно мешать. Span смотрит прямо в память OpenCV, копирования нет.
	//
	// ВАЖНО, и это легко пропустить: Mat.AsSpan<T>() для НЕПРЕРЫВНЫХ данных
	// возвращает пустой Span МОЛЧА — без исключения. Поэтому проверку на
	// непрерывность делаем сами и объясняем проблему понятным текстом.
	//
	// Возвращаемый Span действителен, пока жив Mat, из которого получен,
	// поэтому в вызывающем коде Mat обязан быть объявлен в using
	public static Span<float> AsFloats(Mat output, int minimumCount, string layerName)
	{
		// Выходы DNN OpenCV всегда выделяются одним блоком, но полагаться на это
		// молча нельзя: если предположение перестанет выполняться, лучше явная
		// ошибка здесь, чем тихо испорченные координаты рамок на экране
		if (!output.IsContinuous())
		{
			// Указываем имя слоя: в моделях их десятки, и по одному этому тексту
			// понятно, где искать проблему
			throw new InvalidOperationException(
				$"Выход слоя «{layerName}» не непрерывен, читать его данные нельзя. " +
				"Скорее всего, скачана другая версия модели.");
		}

		// Получаем данные Mat без копирования.
		// Для трёхмерного одно-канального float32-выхода AsSpan корректно отдаёт
		// все элементы подряд в порядке, в котором их читает OpenCV
		var data = output.AsSpan<float>();

		// Проверяем, что элементов достаточно. Меньше нужного означает, что модель
		// выдала не тот набор выходов, на который рассчитан декодер.
		// Размер проверяем именно здесь, потому что дальше индексы считаются вручную
		// и «выход за границу» проявился бы как случайный мусор на экране
		if (data.Length < minimumCount)
		{
			// Показываем и сколько получили, и сколько ждали: по этим двум числам
			// сразу видно, что скачана не та версия модели
			throw new InvalidOperationException(
				$"Выход слоя «{layerName}» содержит {data.Length} значений, " +
				$"а декодер ожидает не меньше {minimumCount}. " +
				"Скорее всего, скачана другая версия модели.");
		}

		// Отдаём данные вызывающему коду
		return data;
	}
}
