// Подключаем OpenCV для работы с изображением
using OpenCvSharp;

// Подключаем геометрию интерфейса
using Microsoft.Maui.Graphics;

// Подключаем способ достать исходный массив из участка памяти без копирования
using System.Runtime.InteropServices;

// Подключаем наши модели данных камеры и распознавания
using MauiBluethooth.Models.Camera;
using MauiBluethooth.Models.Detection;

// Подключаем контракт камеры и каталог моделей
using MauiBluethooth.Services;

// Объявляем пространство имён для сервисов распознавания
namespace MauiBluethooth.Services.Detection;

// Оркестратор распознавания: превращает кадры камеры в готовые рамки для интерфейса.
//
// ГЛАВНОЕ РЕШЕНИЕ ВСЕГО ЭТОГО КЛАССА: где выполняется обработка.
//
// Обработка идёт СИНХРОННО внутри события кадра, то есть на том же потоке,
// который принёс кадр из камеры. Это сделано сознательно, и вот почему.
//
// Вариант «взять кадр, бросить в очередь, обработать в фоне» кажется
// аккуратнее, но на телефоне он ведёт к плохим последствиям: очередь
// начинает расти, память под кадры утекает, приложение отстаёт от картинки
// на десятки кадров, и на экране показывается то, что было секунду назад.
//
// При синхронной обработке работает обратная связь: пока считается кадр,
// камера не может прислать следующий. В Android за это отвечает настройка
// ImageAnalysis со стратегией «только последний кадр»: пока обработчик занят,
// новые кадры просто не создаются. В итоге приложение всегда показывает
// свежую картинку, память не растёт, а лишние кадры физически не тратятся
// на вычисления, которые всё равно никто не увидит
public sealed class ObjectDetector : IDisposable
{
	// Минимальная уверенность, которую можно выставить ползунком.
	// Ниже 0,05 начинают вылезать рамки мусора, и толку от них нет
	public const float MinScoreThreshold = 0.05f;

	// Максимальная уверенность, которую можно выставить ползунком.
	// Выше 0,95 не найдётся почти ничего: сеть не бывает настолько уверена
	public const float MaxScoreThreshold = 0.95f;

	// Каталог моделей
	private readonly ModelRegistry _registry;

	// Активно выбранная модель. Может быть null, пока модель грузится.
	//
	// ПОЧЕМУ ПОЛЯМ НУЖЕН ЗАМОК: поле меняется на одном потоке, а читается на другом.
	// Кадры считаются на потоке камеры, а смена модели приходит из UI-потока.
	// В момент переключения детектор освобождает старую сеть — а на этом же
	// потоке камеры вполне может идти вызов Detect по ЭТОЙ ЖЕ сети.
	// Нативный код не проверяет освобождён ли объект: без замка это прямой
	// вызов функции по освобождённому адресу, то есть падение без сообщения
	private IDetectionModel? _model;

	// Замок, защищающий поле _model и сам вызов Detect
	private readonly Lock _modelLock = new();

	// Буфер под кадр в формате BGR. Переиспользуется между кадрами
	private Mat? _bgrBuffer;

	// Буфер под кадр в экранной ориентации (после поворота и отражения)
	private Mat? _displayBuffer;

	// Список найденных объектов. Переиспользуется между кадрами
	private readonly List<DetectedObject> _results = [];

	// Признак, что объект освобождён. После освобождения события отписываются
	private bool _disposed;

	// Признак, что модель уже загружалась.
	// Нужен, потому что страницу камеры можно открыть много раз, а каждая
	// загрузка YOLOX стоит больше секунды. Без этой проверки при каждом
	// возврате на экран модель читалась бы с диска заново
	private bool _initialized;

	// Конструктор детектора
	public ObjectDetector(ModelRegistry registry)
	{
		// Сохраняем каталог моделей
		_registry = registry;

		// Список моделей для выпадающего списка
		AvailableModels = _registry.Models;

		// По умолчанию модель выбрана, но ещё не загружена
		SelectedModel = _registry.DefaultModel;
	}

	// Событие: пришёл готовый результат по очередному кадру.
	// Подписчику отдаётся НЕИЗМЕНЯЕМЫЙ снимок: в нём нельзя случайно
	// испортить чужие рамки, и его можно спокойно держать на экране
	public event EventHandler<DetectionSnapshot>? SnapshotReady;

	// Событие: обновилась диагностика (замеры времени по этапам)
	public event EventHandler<DetectionDiagnostics>? DiagnosticsReady;

	// Событие: с моделью что-то случилось (ошибка загрузки, несовместимость).
	// Отдельное событие нужно, чтобы интерфейс мог показать сообщение,
	// не ломая саму обработку кадров
	public event EventHandler<string>? ModelFailed;

	// Все доступные модели для выпадающего списка
	public IReadOnlyList<ModelDescriptor> AvailableModels { get; }

	// Какая модель выбрана пользователем
	public ModelDescriptor SelectedModel { get; private set; }

	// Порог уверенности: рамки слабее этого порога не показываются
	public float ScoreThreshold { get; set; } = 0.5f;

	// Включено ли распознавание.
	//
	// Пока выключено, обработчик кадров выходит сразу же, не заходя даже
	// в OpenCV. Это важно для батареи: выключенный детектор не должен
	// ни потреблять память, ни будить процессор
	public bool IsEnabled { get; set; } = true;

	// Создаёт обработчик и загружает выбранную модель.
	// Вызывается один раз при старте страницы камеры, обязательно не из UI-потока
	public async Task InitializeAsync(CancellationToken cancellationToken = default)
	{
		// Если модель уже в памяти — повторно ничего не делаем.
		// Проверка именно на флаг, а не на null модели: модель могла не загрузиться
		// по ошибке, и тогда повторная попытка пользователю не повредит
		if (_initialized)
		{
			// Уже инициализирован — выходим
			return;
		}

		// Помечаем инициализацию ДО загрузки.
		// Если загрузка упадёт, следующий вызов не должен зависнуть в бесконечных
		// повторах, но и не должен молча считаться успешным
		_initialized = true;

		// Загружаем выбранную модель
		await LoadModelAsync(SelectedModel, cancellationToken);
	}

	// Переключает модель распознавания.
	//
	// Смена модели — это чтение с диска и создание нового объекта сети,
	// то есть работа на десятки миллисекунд, а для большой модели — на секунды.
	// Поэтому делаем это асинхронно и обязательно вне UI-потока
	public async Task SwitchModelAsync(ModelDescriptor model, CancellationToken cancellationToken = default)
	{
		// Запоминаем выбор сразу, чтобы интерфейс показал новое название
		// ещё до того, как модель реально загрузится
		SelectedModel = model;

		// Загружаем её
		await LoadModelAsync(model, cancellationToken);
	}

	// Загружает модель и подменяет ею текущую
	//
	// ПОРЯДОК ДЕЙСТВИЙ ЗДЕСЬ ВАЖЕН, И ОН ПРОТИВОПОЛОЖЕН ТОМУ, КАК ПОДСКАЗЫВАЕТ ИНТУИЦИЯ.
	// Сначала загружается НОВАЯ модель, и только потом освобождается старая — под замком.
	//
	// Почему не наоборот. Если освободить старую до загрузки новой, между этими
	// двумя действиями получается окно в секунду и больше, в течение которого
	// детектор вообще ничем не считает: кадры приходят, а обрабатывать их нечем.
	// Каждый такой переход — провал в обнаружении, хорошо заметный глазом.
	//
	// Цена другого порядка: на время чтения файла в памяти живут две сети,
	// то есть для YOLOX это лишние тридцать с лишним мегабайт. Это честный
	// размен: полсекунды «пустых» кадров против тридцати мегабайт на короткий
	// момент переключения. Для телефона дешёвая память важнее
	private async Task LoadModelAsync(ModelDescriptor model, CancellationToken cancellationToken)
	{
		// Создаём новую модель. Это самая долгая часть: чтение файла и создание
		// нативной сети. Замок на этом шаге НЕ держим, потому что await внутри
		// блокировки означал бы, что поток камеры ждёт всю загрузку модели
		IDetectionModel? loaded = null;

		try
		{
			// Загружаем и создаём модель
			loaded = await _registry.CreateAsync(model, cancellationToken);

			// Подменяем модель под замком.
			// Замок нужен ровно здесь: он не даёт потоку камеры войти в Detect
			// по модели, которую мы сейчас освободим. И наоборот — если кадр
			// уже считается, мы подождём, пока он закончится
			lock (_modelLock)
			{
				// Освобождаем старую модель с её нативной сетью.
				// К этому моменту она точно никем не используется: замок мы держим
				_model?.Dispose();

				// Запоминаем новую
				_model = loaded;
			}
		}
		catch (Exception ex)
		{
			// Загрузка не удалась. Созданную модель, если она успела появиться,
			// освобождаем: незагруженная сеть в памяти только занимает место
			loaded?.Dispose();

			// Ошибка загрузки — не повод ронять приложение: камера продолжит
			// работать, просто рамки показываться не будут. Пользователю говорим,
			// что именно произошло, и оставляем старую модель работать,
			// если она была
			ModelFailed?.Invoke(this, $"Не удалось загрузить модель «{model.DisplayName}»: {ex.Message}");
		}
	}

	// Обрабатывает очередной кадр камеры.
	//
	// Метод вызывается на потоке камеры, а не в UI-потоке.
	// Всё, что здесь происходит, должно быть быстрым и не должно трогать интерфейс
	private void OnFrameReceived(object? sender, CameraFrame frame)
	{
		// Проверяем, что объект ещё жив: после закрытия страницы подписка снимается,
		// но между отпиской и закрытием камеры может прийти кадр
		if (_disposed)
		{
			// Объект освобождён — кадр игнорируем
			return;
		}

		// Выключено распознавание — выходим сразу.
		// Проверка стоит ДО всего остального: это самая частая ситуация
		// при выключенном детекторе, и лишняя работа недопустима
		if (!IsEnabled)
		{
			// Детектор выключен — кадр не нужен
			return;
		}

		// Проверяем модель под замком.
		//
		// Отдельная проверка внутри блокировки, а не простое чтение поля, сделана
		// намеренно: между проверкой и вызовом Detect в другом потоке может
		// произойти переключение модели. Ещё раз под замком мы кладём модель
		// в локальную переменную, и весь дальнейший код работает именно с ней
		IDetectionModel? model;

		lock (_modelLock)
		{
			// Модель ещё грузится или не загрузилась
			model = _model;
		}

		// Нечего обрабатывать
		if (model is null)
		{
			// Выходим: считать пока нечем
			return;
		}

		// Замеряем весь конвейер целиком
		var frameStart = DetectionDiagnostics.Clock.Elapsed.TotalMilliseconds;

		try
		{
			// ШАГ 1. Оборачиваем пиксели кадра в матрицу OpenCV БЕЗ копирования.
			//
			// Камера уже отдаёт плотно упакованный массив, поэтому матрица
			// просто указывает на те же байты. Копирования нет — а это миллионы
			// мегабайт в секунду, если копировать каждый кадр
			//
			// ВНИМАНИЕ, здесь легко ошибиться. Для кадра в памяти есть удобный
			// вызов ToArray(), но он КОПИРУЕТ все байты заново. На кадре 1080p
			// это восемь мегабайт на каждый кадр, а кадры идут десятками в секунду.
			// Нужен именно исходный массив: достаём его из сегмента памяти,
			// не копируя ни байта
			if (!MemoryMarshal.TryGetArray(frame.Data, out var segment))
			{
				// Кадр лежит не в обычном массиве. Сейчас камера так не отдаёт,
				// но если появится новый источник кадров (например, видеофайл),
				// лучше узнать об этом сразу, чем молча получать нули в рамках
				ModelFailed?.Invoke(this, "Кадр камеры не лежит в обычном массиве, распознавание пропущено.");
				return;
			}

			// TryGetArray может вернуть true даже с пустым массивом внутри
			// (например, на пустой памяти). Передавать null в OpenCV нельзя —
			// это даст «Object reference not set…» без объяснения
			if (segment.Array is null)
			{
				ModelFailed?.Invoke(this, "Кадр камеры не содержит массива пикселей, распознавание пропущено.");
				return;
			}

			// Оборачиваем байты кадра в матрицу 4 байта на пиксель.
			// Тип CV_8UC4 — это 8 бит на канал, 4 канала: подходит и для RGBA, и для BGRA
			using var source = Mat.FromPixelData(
				frame.Height,
				frame.Width,
				MatType.CV_8UC4,
				segment.Array,
				frame.Stride);

			// ШАГ 2. Приводим к BGR — так OpenCV ожидает цвет.
			// Android отдаёт RGBA, Windows BGRA, а порядок каналов модели
			// у всех трёх сетей разный, поэтому порядок приводим здесь, один раз
			var convertStart = DetectionDiagnostics.Clock.Elapsed.TotalMilliseconds;
			var bgr = EnsureBgrBuffer(frame.Width, frame.Height);
			Cv2.CvtColor(
				source,
				bgr,
				frame.PixelFormat == CameraPixelFormat.Rgba
					? ColorConversionCodes.RGBA2BGR
					: ColorConversionCodes.BGRA2BGR);
			var convertMs = DetectionDiagnostics.Clock.Elapsed.TotalMilliseconds - convertStart;

			// ШАГ 3. Поворачиваем и отражаем кадр в экранную ориентацию.
			//
			// Зачем это здесь, а не в каждой модели. Смысл в том, чтобы все
			// модели получали картинку ровно в том виде, в каком её видит человек,
			// и отдавали рамки сразу в координатах экрана. Иначе каждой модели
			// пришлось бы знать про поворот и зеркальность камеры, а оверлею —
			// ещё и разворачивать каждую рамку обратно. Одна конвенция
			// на всех понятнее, чем одно и то же в шести местах
			var transformStart = DetectionDiagnostics.Clock.Elapsed.TotalMilliseconds;
			var display = EnsureDisplayBuffer(bgr, frame.Geometry);
			var transformMs = DetectionDiagnostics.Clock.Elapsed.TotalMilliseconds - transformStart;

			// ШАГ 4. Собственно распознавание. Здесь модель сама вписывает кадр
			// в свой квадратный вход и возвращает рамки в координатах кадра.
			//
			// Вызов под замком — обязательное требование, а не перестраховка.
			// Пока идёт Detect, другая модель уйти не может: смена модели ждёт
			// здесь же. Без замка переключение освободило бы нативную сеть
			// посреди вычисления, и это вызвало бы падение без сообщения
			TimingStage[] modelStages;

			lock (_modelLock)
			{
				// Считаем по выбранной модели
				model.Detect(display, ScoreThreshold, _results);

				// Забираем замеры модели тут же, под тем же замком.
				// После выхода из блокировки модель могла бы быть подменена,
				// и тогда мы прочитали бы уже не те данные
				modelStages = [.. model.LastStages];
			}

			// ШАГ 5. Собираем неизменяемый снимок.
			//
			// Список копируется, а не передаётся на правах ссылки. Иначе
			// следующий кадр, придя на этом же потоке камеры, начал бы
			// переписывать прямоугольник, который интерфейс ещё рисует
			var objects = new DetectedObject[_results.Count];
			_results.CopyTo(objects);

			// Собираем снимок целиком
			var snapshot = new DetectionSnapshot
			{
				// Кладём копию списка объектов
				Objects = objects,

				// Запоминаем, какой моделью получен результат
				ModelId = model.Descriptor.Id,

				// Запоминаем категорию модели
				Kind = model.Descriptor.Kind,

				// Метка времени кадра: по ней интерфейс может отбросить
				// устаревший результат, если кадры почему-то перестали приходить
				FrameTimestampMilliseconds = frame.TimestampMilliseconds,

				// Размеры кадра нужны оверлею, чтобы пересчитать координаты
				// под свой фактический размер на экране
				FrameWidth = frame.Geometry.DisplayWidth,
				FrameHeight = frame.Geometry.DisplayHeight
			};

			// Отдаём снимок подписчикам.
			// ПОЧЕМУ ЗДЕСЬ НЕТ MainThread: подписчиком будет ViewModel,
			// и перенос в UI-поток — его дело. Смешивать тут ещё и
			// переключение потоков означало бы, что обработчик кадра
			// ждёт, пока UI освободится, а это снова затормозило бы кадры
			SnapshotReady?.Invoke(this, snapshot);

			// Собираем диагностику: замеры детектора плюс замеры самой модели
			var stages = new List<TimingStage>(capacity: 8)
			{
				// Порядок по времени выполнения — так список читается как история кадра
				new("Формат BGR", convertMs),
				new("Поворот и отражение", transformMs)
			};

			// Добавляем замеры, сделанные внутри модели: у каждой свои этапы
			stages.AddRange(modelStages);

			// Отдаём диагностику подписчикам
			DiagnosticsReady?.Invoke(this, new DetectionDiagnostics(
				model.Descriptor.Id,
				stages,
				objects.Length,
				frame.TimestampMilliseconds));
		}
		catch (Exception ex)
		{
			// Ошибка в одном кадре не должна ронять приложение.
			// Но и молчать нельзя: если модель несовместима с телефоном,
			// пользователь должен это увидеть, а не гадать, почему нет рамок.
			// Сообщаем один раз — на каждый кадр такое слать бессмысленно
			//
			// К тексту добавляем первую строку стека: для NRE это единственный
			// способ сразу увидеть в интерфейсе, какой именно шаг упал
			var source = ex.StackTrace?.Split('\n').FirstOrDefault()?.Trim();
			ModelFailed?.Invoke(this,
				$"Ошибка распознавания: {ex.Message}{(string.IsNullOrEmpty(source) ? string.Empty : $"\n{source}")}");

			// Полный стек ошибки — в журнал и в отладчик.
			// В отладчике он виден сразу в Output-окне, а не только в logcat
			Console.Error.WriteLine($"[ObjectDetector] Ошибка кадра распознавания: {ex}");
			System.Diagnostics.Debug.WriteLine($"[ObjectDetector] Ошибка кадра распознавания: {ex}");

			// Дальше кадр пропускаем и ждём следующего
		}
	}

	// Возвращает буфер под BGR-кадр нужного размера, создавая его при необходимости.
	//
	// Зачем переиспользуем буфер, а не создаём новый Mat на каждый кадр.
	// Mat — это обёртка над нативной памятью вне управляемой кучи: новый Mat
	// означает новый malloc на стороне OpenCV. На десяти кадрах в секунду
	// за минуту это сотни мегабайт служебной памяти и заметная нагрузка
	// на сборщик мусора. Один буфер, переиспользуемый между кадрами,
	// убирает и то и другое
	private Mat EnsureBgrBuffer(int width, int height)
	{
		// Если буфер уже того же размера — берём его
		if (_bgrBuffer is not null && _bgrBuffer.Width == width && _bgrBuffer.Height == height)
		{
			// Размер совпал, переиспользуем
			return _bgrBuffer;
		}

		// Размер изменился: старый буфер больше не подходит
		_bgrBuffer?.Dispose();

		// Создаём новый под нужный размер
		_bgrBuffer = new Mat(height, width, MatType.CV_8UC3);

		// Отдаём готовый буфер
		return _bgrBuffer;
	}

	// Приводит BGR-кадр к экранной ориентации и возвращает результат.
	//
	// Если поворот и отражение не нужны, возвращаем исходный буфер как есть —
	// лишнее копирование в этом случае просто тратит время
	private Mat EnsureDisplayBuffer(Mat bgr, CameraFrameGeometry geometry)
	{
		// Собираем флаги того, что надо сделать с картинкой
		var needsRotation = geometry.RotationDegrees is 90 or 180 or 270;
		var needsMirror = geometry.IsMirrored;

		// Ни поворота, ни отражения: отдаём кадр как есть.
		// Для кадров 4:3 с поворотом 0 это заметная экономия:
		// пропускаем целое копирование полноразмерного кадра
		if (!needsRotation && !needsMirror)
		{
			// Картинка уже в нужной ориентации
			return bgr;
		}

		// Подбираем буфер под результат: при повороте на 90 или 270
		// ширина и высота меняются местами
		var width = geometry.DisplayWidth;
		var height = geometry.DisplayHeight;
		// Создаём буфер заново только если размер изменился.
		// При повороте на 90 или 270 градусов ширина и высота меняются местами,
		// поэтому сравниваем именно с теми размерами, которые ожидаем сейчас
		if (_displayBuffer is null || _displayBuffer.Width != width || _displayBuffer.Height != height)
		{
			// Размер изменился — освобождаем старый буфер и создаём новый
			_displayBuffer?.Dispose();

			// Новый буфер под результат преобразования
			_displayBuffer = new Mat(height, width, MatType.CV_8UC3);
		}

		// Работаем с текущим буфером результата
		var target = _displayBuffer;

		// Сначала поворот, если он нужен.
		// ПОРЯДОК ВАЖЕН: сначала поворот, потом отражение.
		// Если сделать наоборот, то фронтальная камера отразится не в ту сторону,
		// и надпись на заднем плане кадра прочитать будет невозможно
		if (needsRotation)
		{
			// Выбираем флаг поворота по градусам.
			//
			// ВНИМАНИЕ, ЗДЕСЬ ЛЕГКО ПЕРЕПУТАТЬ НАПРАВЛЕНИЕ.
			// Имя Rotate90Clockwise означает «повернуть на 90 градусов ПО часовой стрелке».
			// Это не синоним поворота на 90 градусов в любую сторону, и путать их легко.
			// Ровно наоборот, Rotate90Counterclockwise — это поворот на 270 градусов по часовой.
			// Если поменять эти два флага местами, картинка встанет боком,
			// и это будет выглядеть как «камера сломалась», а не как ошибка в коде
			var rotateFlag = geometry.RotationDegrees switch
			{
				// На 90 градусов по часовой стрелке
				90 => RotateFlags.Rotate90Clockwise,

				// На 180 градусов: направление неважно
				180 => RotateFlags.Rotate180,

				// На 90 градусов против часовой стрелки
				_ => RotateFlags.Rotate90Counterclockwise
			};

			// Поворачиваем картинку
			Cv2.Rotate(bgr, target, rotateFlag);
		}
		else
		{
			// Поворота нет, но отражение есть: копируем исходный кадр
			// в буфер результата, потому что отражать будем уже его
			bgr.CopyTo(target);
		}

		// Теперь отражаем по горизонтали, если камера фронтальная
		if (needsMirror)
		{
			// Отражение выполняется НА ТОТ ЖЕ буфер, а не в новый.
			// Второй Mat здесь был бы лишней полной копией кадра
			//
			// ИМЯ СОМБИРНОЕ, ПОЭТОМУ ПРОПИСЫВАЮ СМЫСЛ ЯВНО.
			// FlipMode.X означает отражение ОТНОСИТЕЛЬНО ОСИ X, а ось X
			// в картинке идёт слева направо. Значит X — это зеркало
			// «лево-право», то есть привычное отражение для селфи.
			// Ось Y идёт сверху вниз, поэтому FlipMode.Y перевернул бы
			// картинку вверх ногами, а это совсем не то, что нужно
			Cv2.Flip(target, target, FlipMode.X);
		}

		// Отдаём готовый кадр в экранной ориентации
		return target;
	}

	// Подписывается на кадры камеры.
	//
	// Отдельный метод, а не подписка в конструкторе: модель грузится асинхронно,
	// и событие должно появиться только когда обработчик действительно готов
	public void AttachToCamera(ICameraService cameraService)
	{
		// Подписываемся на кадры
		cameraService.FrameReceived += OnFrameReceived;
	}

	// Отписывается от кадров камеры.
	// Без этого обработчик остался бы подписанным на закрытую камеру
	// и удерживал бы её нативные ресурсы
	public void DetachFromCamera(ICameraService cameraService)
	{
		// Снимаем подписку
		cameraService.FrameReceived -= OnFrameReceived;
	}

	// Освобождает модель и нативные буферы
	//
	// Замок обязателен и здесь: метод вызывается при закрытии приложения,
	// когда кадры уже не приходят, но если вызвать его раньше, пока кадр
	// считается, получится тот же вызов по освобождённому адресу
	private void DisposeModel()
	{
		// Под тем же замком, что и вызов Detect
		lock (_modelLock)
		{
			// У модели внутри есть нативная сеть, её нужно освободить явно
			_model?.Dispose();

			// Забываем модель
			_model = null;
		}
	}

	// Освобождает все ресурсы детектора
	public void Dispose()
	{
		// Повторный вызов Dispose ничего не ломает, но и лишнюю работу делать не надо
		if (_disposed)
		{
			// Уже освобождён — выходим
			return;
		}

		// Помечаем объект освобождённым: приходящие кадры он теперь игнорирует
		_disposed = true;

		// Освобождаем модель с её нативной сетью
		DisposeModel();

		// Освобождаем буферы кадров под тем же замком.
		//
		// Буферы тоже нативная память, и к ним примени ровно то же рассуждение,
		// что и к сети: если кадр уже начал в них писать, освобождать их нельзя.
		// Флаг _disposed выше гарантирует, что новые кадры сюда не зайдут,
		// а замок дожидается того, который уже вошёл
		lock (_modelLock)
		{
			// Буфер BGR
			_bgrBuffer?.Dispose();

			// Буфер экранной ориентации
			_displayBuffer?.Dispose();
		}
	}
}
