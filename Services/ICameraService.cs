// Подключаем пространство имён с моделями кадра, камер и результата запуска
using MauiBluethooth.Models.Camera;

// Объявляем собственное пространство имён для сервисного слоя приложения
namespace MauiBluethooth.Services;

// Интерфейс — контракт камерного сервиса, который реализуется отдельно под каждую платформу (Android, Windows).
// Смысл разделения: код представления (ViewModel, страница, handler) не знает, какая камера под ним — системная камера
// Android (CameraX) или MediaCapture в Windows. Вся разница спрятана в реализации
public interface ICameraService
{
	// Событие: пришёл очередной кадр с камеры. Вызывается на фоновом потоке платформы (не в UI-потоке!)
	event EventHandler<CameraFrame>? FrameReceived;

	// Список доступных камер, найденных на устройстве. Заполняется при инициализации платформы
	IReadOnlyList<CameraOption> CameraOptions { get; }

	// Идентификатор выбранной камеры (тот, что будет открыт при StartAsync)
	string? SelectedCameraId { get; }

	// Геометрия последнего полученного кадра (поворот, зеркальность). null, пока кадров не было.
	// Нужна оверлею, чтобы нарисовать рамку в тех же координатах, что и видео
	CameraFrameGeometry? FrameGeometry { get; }

	// Признак того, что камера сейчас запущена и кадры приходят
	bool IsRunning { get; }

	// Признак того, что пользователь не дал разрешение на камеру.
	// По нему UI показывает кнопку «Открыть настройки», потому что повторный запрос уже не поможет
	bool PermissionDenied { get; }

	// Создаёт нативный элемент предпросмотра (PreviewView на Android, MediaPlayerElement на Windows).
	// Возвращается object, потому что тип у каждой платформы свой и не имеет общего базового класса в MAUI
	object CreatePlatformPreview();

	// Запуск камеры: запрашивает разрешение, инициализирует платформу и включает поток кадров.
	// Возвращает результат с флагом успеха и текстом ошибки для показа пользователю
	Task<CameraStartResult> StartAsync();

	// Остановка камеры и освобождение нативных ресурсов (MediaCapture, CameraX use cases)
	Task StopAsync();

	// Переключение на другую камеру по её идентификатору. Возвращает true, если переключение удалось
	Task<bool> SelectCameraAsync(string cameraId);

	// Сообщаем сервису, находится ли страница камеры на экране.
	// Нужно для HandleAppResumeAsync: возобновлять поток кадров имеет смысл только для видимой страницы
	void SetPageActive(bool isActive);

	// Обработка ухода приложения в фон: обязательно освобождаем камеру,
	// иначе другие приложения её не смогут открыть (а на Android система может убить процесс)
	Task HandleAppSleepAsync();

	// Обработка возврата приложения из фона: запускаем камеру заново, если она была нужна
	Task HandleAppResumeAsync();
}
